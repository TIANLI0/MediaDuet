"""Single source of truth for the MediaDuet logo on every platform.

The mark: two interlocking rings (the PC and the phone, in duet), white on a flat
violet rounded square. No gradients. Geometry is defined once (fractions of the
icon's visible size) and used for:
  * Windows: app.ico, tray_on.ico, tray_off.ico, app_512.png (host) and the
    WinUI Assets/MediaDuet.ico + MediaDuet.png;
  * Android: adaptive icon foreground / monochrome vectors, background colour,
    and the status-bar (notification) icon.

Usage:  python -I tools/make_icons.py
"""
import os
import re

from PIL import Image, ImageDraw

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

BRAND = (0x6E, 0x56, 0xCF)        # flat violet
BRAND_HEX = "#FF6E56CF"
OFF = (0x7A, 0x7A, 0x84)          # tray "disconnected"
RING = (255, 255, 255)

# Geometry as fractions of the visible icon size.
CENTER_OFFSET = 0.12   # each ring's centre is this far left/right of the middle
RADIUS = 0.24          # ring radius (to the middle of the stroke)
STROKE = 0.085         # ring stroke width
CORNER = 0.22          # rounded-square corner radius (Windows)


def render(size, bg, ss=4):
    S = size * ss
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, S - 1, S - 1], radius=int(S * CORNER), fill=bg + (255,))
    w = max(2, int(S * STROKE))
    r = S * RADIUS
    for cx in (S * (0.5 - CENTER_OFFSET), S * (0.5 + CENTER_OFFSET)):
        cy = S / 2
        d.ellipse([cx - r - w / 2, cy - r - w / 2, cx + r + w / 2, cy + r + w / 2], outline=RING + (255,), width=w)
    return img.resize((size, size), Image.LANCZOS)


def save_ico(path, bg, sizes):
    imgs = [render(s, bg) for s in sizes]
    imgs[-1].save(path, format="ICO", sizes=[(s, s) for s in sizes], append_images=imgs[:-1])


def ring_paths(view, visible, color_attr):
    """Two stroked circles in a square viewport; `visible` = size of the visible area."""
    c = view / 2
    off, r, w = visible * CENTER_OFFSET, visible * RADIUS, visible * STROKE
    out = []
    for cx in (c - off, c + off):
        out.append(
            f'    <path {color_attr} android:strokeWidth="{w:.2f}" android:fillColor="#00000000"\n'
            f'        android:pathData="M{cx - r:.2f},{c:.2f}a{r:.2f},{r:.2f} 0,1 0,{2 * r:.2f},0'
            f'a{r:.2f},{r:.2f} 0,1 0,{-2 * r:.2f},0" />')
    return "\n".join(out)


def vector(view, size_dp, visible, color_attr, comment):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} Generated by tools/make_icons.py. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{view}" android:viewportHeight="{view}">\n'
            f'{ring_paths(view, visible, color_attr)}\n</vector>\n')


def main():
    # ---------------- Windows host
    res = os.path.join(ROOT, "windows", "app", "resources")
    save_ico(os.path.join(res, "app.ico"), BRAND, [16, 20, 24, 32, 40, 48, 64, 128, 256])
    save_ico(os.path.join(res, "tray_on.ico"), BRAND, [16, 20, 24, 32, 40, 48])
    save_ico(os.path.join(res, "tray_off.ico"), OFF, [16, 20, 24, 32, 40, 48])
    render(512, BRAND).save(os.path.join(res, "app_512.png"))
    # ---------------- WinUI
    ui = os.path.join(ROOT, "windows", "ui", "Assets")
    if os.path.isdir(ui):
        save_ico(os.path.join(ui, "MediaDuet.ico"), BRAND, [16, 20, 24, 32, 40, 48, 64, 128, 256])
        render(256, BRAND).save(os.path.join(ui, "MediaDuet.png"))
    # ---------------- Android (adaptive icon: 108dp canvas, 72dp visible, 66dp safe zone)
    ares = os.path.join(ROOT, "android", "app", "src", "main", "res")
    if os.path.isdir(ares):
        dr = os.path.join(ares, "drawable")
        open(os.path.join(dr, "ic_launcher_foreground.xml"), "w", encoding="utf-8", newline="\n").write(
            vector(108, 108, 72, 'android:strokeColor="#FFFFFFFF"', "Launcher foreground: the MediaDuet rings."))
        open(os.path.join(dr, "ic_launcher_monochrome.xml"), "w", encoding="utf-8", newline="\n").write(
            vector(108, 108, 72, 'android:strokeColor="#FF000000"', "Themed (monochrome) launcher icon."))
        open(os.path.join(dr, "ic_stat_link.xml"), "w", encoding="utf-8", newline="\n").write(
            vector(24, 24, 24, 'android:strokeColor="#FFFFFFFF"', "Status-bar icon: the MediaDuet rings."))
        colors = os.path.join(ares, "values", "colors.xml")
        text = open(colors, encoding="utf-8").read()
        text = re.sub(r'(<color name="launcher_background">)[^<]*(</color>)', r"\g<1>" + BRAND_HEX + r"\g<2>", text)
        open(colors, "w", encoding="utf-8", newline="\n").write(text)
    render(512, BRAND).save(os.path.join(ROOT, "docs", "logo.png"))
    print("icons regenerated")


if __name__ == "__main__":
    main()
